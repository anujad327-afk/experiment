class MATH:
    def add(self,a,b):
        print('the sumation is:',a+b)
    def mul(self,a,b):
        print('the sumation is:',a*b)
    def sub(self,a,b):
        print('the sumation is:',a-b) 
    def div(self,a,b):
        print('the sumation is:',a/b)


obj = MATH()
obj.add(10,20)
obj.mul(10,30)
obj.sub(30,40)
obj.div(30,20)